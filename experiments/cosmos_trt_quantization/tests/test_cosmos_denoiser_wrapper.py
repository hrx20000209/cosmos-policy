"""Validation assertions over the captured real-network wrapper run.

The heavy fixture is generated by ``scripts/capture_denoiser_inputs.py``.
This test stays light and verifies that the recorded run passed all required
numerical and structural gates.
"""

import json
from pathlib import Path


EXP = Path(__file__).resolve().parents[1]


def test_recorded_wrapper_equivalence():
    result = json.loads((EXP / "summaries/denoiser_wrapper_validation.json").read_text())
    output = result["output"]
    assert result["batch_size"] == 1
    assert result["chunk_size"] == 16
    assert output["cosine_vs_direct"] > 0.99999
    assert output["finite"]
    assert output["repeat_max_abs"] == 0
    assert len(output["shape"]) == 5

